/** True for the base-36 length digits, false for the capital that starts a run. */
const isDigit = (code: number) => code < 65 || code > 90;

/** The biome index of every square, unpacked from the run lengths. */
export function earthBiomes(): Uint8Array {
  const out = new Uint8Array(W * H);
  let at = 0;
  for (let i = 0; i < EARTH_RLE.length; ) {
    const biome = EARTH_RLE.charCodeAt(i++) - 65;
    const from = i;
    while (i < EARTH_RLE.length && isDigit(EARTH_RLE.charCodeAt(i))) i++;
    const run = parseInt(EARTH_RLE.slice(from, i), 36);
    out.fill(biome, at, at + run);
    at += run;
  }
  if (at !== W * H) throw new RangeError(`earth map unpacked to ${at} of ${W * H} squares`);
  return out;
}
